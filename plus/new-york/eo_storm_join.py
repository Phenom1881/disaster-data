"""Cross-reference Virginia emergency declarations with NCEI Storm Events.

For each declaration, this script finds Virginia events whose begin date falls
within a configurable window around the signing date.  NCEI can report an event
against a county/county-equivalent (CZ_TYPE=C), an NWS public forecast zone
(CZ_TYPE=Z), or a marine zone (CZ_TYPE=M).  The output preserves that distinction
so a forecast zone is not silently presented as a legal locality.

Hazard filtering: a declaration's description is scanned for recognized hazard
keywords (drought, wildfire, flood, hurricane, winter, tornado, wind, plus a
broader storm/storm-related/nor'easter/weather-conditions catch-all, used only
as a fallback when nothing more specific matched) to decide which NCEI
EVENT_TYPE values are plausible matches. "Water emergency" is deliberately
NOT auto-classified - see compatible_event_types()'s docstring and the
"water" category's own comment in HAZARD_EVENT_TYPES for why a keyword alone
cannot safely tell a drought-driven water emergency apart from a
hurricane-driven one. When a description matches NONE of the recognized
keywords - a generic title like "Declaration of a State of Emergency" with
no hazard-specific language - the match is AMBIGUOUS. By default an
ambiguous declaration is skipped (no NCEI search is attempted for it) rather
than silently matching every recorded event type in the window, which
previously produced large, unrelated result sets for generically-titled
declarations. Pass --unmatched-hazard-policy all to opt into that old
behavior explicitly for an entire run; every declaration this affects is
printed as a warning either way, and summarized again at the end of the run.

A single declaration can also carry its own reviewed answer via an optional
hazard_category_override column, instead of waiting on a run-wide flag - see
resolve_override() for the exact format. This is the mechanism for clearing
one generically-titled declaration at a time (e.g. after reading its source
document) without changing behavior for the rest of the state's declarations.

The recommended way to apply reviewed overrides is a durable sidecar file
(--overrides plus/<state>/hazard_overrides.csv), NOT editing
declarations_for_join.csv directly - that file is regenerated by each
collection run and would silently lose any override written into it. See
load_overrides() and apply_overrides() for the sidecar schema, including the
reserved "exclude" value for dropping non-weather records (administrative,
procurement, memorial, policy orders, etc.) from the join entirely.

Required input columns:
  eo_number,event_description,date_signed

Historical inventories may also supply declaration_id, governor,
archive_record_url, and hazard_category_override.  Those fields are retained
in both outputs (except hazard_category_override, which is consumed here and
not carried into the match/severity CSVs).  A stable declaration_id is
important because EO numbers repeat across administrations.

Usage:
  python eo_storm_join.py --declarations declarations_for_join.csv --out matches.csv
"""

