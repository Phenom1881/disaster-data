_year_cache = {}


def get_latest_filenames_by_year():
    """Return the most recently certified details filename for each year."""
    response = requests.get(INDEX_URL, timeout=30)
    response.raise_for_status()
    latest = {}
    for match in FILE_PATTERN.finditer(response.text):
        year, certification_date = match.group(1), match.group(2)
        filename = match.group(0)
        if year not in latest or certification_date > latest[year][1]:
            latest[year] = (filename, certification_date)
    return {year: filename for year, (filename, _) in latest.items()}


def download_year_details(filename):
    response = requests.get(INDEX_URL + filename, timeout=60)
    response.raise_for_status()
    with gzip.GzipFile(fileobj=io.BytesIO(response.content)) as archive:
        frame = pd.read_csv(archive, low_memory=False)
    # NCEI stores values such as "24-JAN-26 21:00:00".
    frame["BEGIN_DATE_TIME"] = pd.to_datetime(
        frame["BEGIN_DATE_TIME"], format="%d-%b-%y %H:%M:%S", errors="coerce"
    )
    frame["END_DATE_TIME"] = pd.to_datetime(
        frame["END_DATE_TIME"], format="%d-%b-%y %H:%M:%S", errors="coerce"
    )
    return frame


def get_year_events(year, filenames, state):
    year_text = str(year)
    cache_key = (year_text, state.upper())
    if cache_key in _year_cache:
        return _year_cache[cache_key]
    if year_text not in filenames:
        print(f"No NCEI file published yet for {year_text}.", file=sys.stderr)
        _year_cache[cache_key] = pd.DataFrame()
        return _year_cache[cache_key]
    frame = download_year_details(filenames[year_text])
    # Historical runs span more than two decades.  Retaining only the selected
    # state's records keeps the cache small while still downloading each year once.
    frame = frame[frame["STATE"].fillna("").str.upper() == state.upper()].copy()
    _year_cache[cache_key] = frame
    return _year_cache[cache_key]


def compatible_event_types(description):
    """Infer plausible NCEI event types from an executive-order title.

    Returns an EMPTY set when no recognized hazard keyword is present. Callers
    must not treat an empty set as "no restriction" - see
    resolve_allowed_types(), which is the only place that decision is made.

    storm_general is a deliberately broad fallback for a description that
    ONLY says "storm"/"storm-related"/"nor'easter"/"weather conditions" with
    no more specific hazard word. It must never be unioned alongside an
    already-specific category (winter, tropical, flood, severe_storm, wind,
    fire, drought) - doing so silently reintroduces the same "match nearly
    everything" failure mode this module was built to eliminate, just via a
    different path. A description like "winter storm" contains the bare word
    "storm" as well as "winter"; without this guard, the specific "winter"
    match gets diluted by storm_general's own Flood/Tornado/Thunderstorm
    Wind/Hail/etc., letting a purely winter declaration match an NCEI flood
    or tornado record. Confirmed in production: PA's "A complex winter storm
    system... heavy snow and strong winds" matched a Flood record in
    Armstrong County for exactly this reason (2026-09-05 five-state
    retest). storm_general is therefore only appended when nothing more
    specific already matched.
    """
    text = str(description).lower()
    categories = []
    if "drought" in text:
        categories.append("drought")
    if re.search(r"\b(?:wildfire|forest fire|brush fire)s?\b", text):
        categories.append("fire")
    if re.search(r"\b(?:flood|flooding|rainfall|heavy rain|mudslide|landslide)", text):
        categories.append("flood")
    if re.search(r"\b(?:hurricane|tropical storm|tropical depression|tropical weather)", text):
        categories.append("tropical")
    if re.search(r"\b(?:winter|snow|ice|icing|sleet|blizzard|cold|freeze|freezing)", text):
        categories.append("winter")
    if re.search(r"\b(?:tornado|severe storm|severe weather|thunderstorm|hail|lightning)", text):
        categories.append("severe_storm")
    if re.search(r"\b(?:wind|winds|wind damage)", text):
        categories.append("wind")
    if not categories:
        generic_storm = re.search(
            r"\bstorms?\b|storm[- ]related|nor['\u2019]?\s?easter|noreaster", text
        )
        generic_weather = re.search(r"\bweather[- ]related\b|\bweather conditions?\b", text)
        if generic_storm or generic_weather:
            categories.append("storm_general")
    allowed = set()
    for category in categories:
        allowed.update(HAZARD_EVENT_TYPES[category])
    return allowed


def resolve_override(override_value):
    """Parse an optional, human-reviewed hazard_category_override cell.

    A reviewer who has looked at the source document for a generically-titled
    declaration (a bare "State of Emergency" with no recoverable weather
    keyword) can write the real answer directly into the declarations CSV
    instead of relying on a keyword guess. The value is a comma-separated
    list of either HAZARD_EVENT_TYPES category names (e.g. "flood,tropical")
    or literal NCEI EVENT_TYPE strings drawn from those same categories
    (e.g. "Coastal Flood"), or any mix of the two.

    This exists specifically because --unmatched-hazard-policy applies to an
    entire run, not to one declaration - the 2026-09-05 cross-state
    validation flagged that as a real gap: reviewing NY/NC/NJ's generic
    declarations one at a time needs a per-row mechanism, not a global flag
    that would reintroduce the original over-match risk everywhere else in
    the same run.

    Returns None if override_value is genuinely blank/missing/NaN (no
    override present for this declaration - the normal case). pandas reads
    an empty CSV cell as float NaN, not an empty string, so that check must
    happen before any str()/strip() conversion; treating a stray "nan" as a
    literal token was a real bug in an earlier version of this function.

    Raises ValueError if override_value is non-blank but resolves to zero
    usable tokens (e.g. ", ,") or contains any token that is neither a known
    HAZARD_EVENT_TYPES category name nor a literal EVENT_TYPE value found in
    one of those categories. Both are treated as hard errors, not silently
    downgraded to "no restriction" - an unrecognized or empty override must
    never be allowed to fall through to the "no restriction" meaning that an
    empty set carries elsewhere in this module, since that was exactly the
    original inflation bug.
    """
    if override_value is None or pd.isna(override_value):
        return None

    text = str(override_value).strip()
    if not text:
        return None

    tokens = [token.strip() for token in text.split(",") if token.strip()]
    if not tokens:
        raise ValueError(
            "hazard_category_override contains no usable categories or event types"
        )

    known_event_types = set().union(*HAZARD_EVENT_TYPES.values())
    allowed = set()

    for token in tokens:
        if token in HAZARD_EVENT_TYPES:
            allowed.update(HAZARD_EVENT_TYPES[token])
        elif token in known_event_types:
            allowed.add(token)
        else:
            raise ValueError(
                f"Unknown hazard_category_override value: {token!r}"
            )

    return allowed


def load_overrides(path):
    """Load a durable sidecar hazard-override file.

    Sidecar files are the durable, human-reviewed source of truth for
    declarations a keyword search cannot safely classify. They live outside
    declarations_for_join.csv on purpose: that file is regenerated by each
    collection run and would silently erase any override written directly
    into it. Recommended location: plus/<state>/hazard_overrides.csv.

    Required columns: declaration_id, hazard_category_override.
    Optional columns: review_note, source_url - audit trail only, never
    used for matching logic.

    hazard_category_override accepts everything resolve_override() accepts
    (comma-separated HAZARD_EVENT_TYPES category names and/or literal
    EVENT_TYPE values), plus one reserved value, EXCLUDE_SENTINEL
    ("exclude", case-insensitive), which drops a declaration from the join
    entirely - for records identified as not belonging in the weather input
    at all, which a fresh collection run would otherwise keep re-introducing
    if the fix were only made by deleting rows from the generated CSV.

    Every row is fully normalized and validated here, at load time, before
    anything is merged against the actual declarations or any NCEI request
    is made:
      - declaration_id is trimmed; a blank/NaN/whitespace-only id raises.
      - review_note/source_url are trimmed (blank is fine - they're audit
        text only).
      - hazard_category_override is required to be non-blank for every row.
      - every non-"exclude" hazard_category_override value is validated by
        calling resolve_override() on it - for EVERY row, including rows
        whose declaration_id turns out not to match anything in the current
        declarations CSV. Skipping validation for those would mean a typo
        in an already-stale row (one that will only ever produce an
        unmatched-id warning downstream) could sit in a sidecar file
        indefinitely without ever being caught, which contradicts this
        file's whole point of failing loudly on malformed input.
      - duplicate detection runs AFTER declaration_id is trimmed, so
        "A-1 " and "A-1" are correctly treated as the same id.

    Raises ValueError on any of the above. A malformed sidecar must halt
    the run before any matching starts, not surface later as a silent
    unmatched-id warning or a quietly-wrong match.
    """
    overrides = pd.read_csv(path, dtype=str)
    missing = sorted(REQUIRED_OVERRIDE_COLUMNS.difference(overrides.columns))
    if missing:
        raise ValueError(f"Overrides file {path} is missing: " + ", ".join(missing))
    for column in OPTIONAL_OVERRIDE_COLUMNS:
        if column not in overrides.columns:
            overrides[column] = ""

    overrides["declaration_id"] = (
        overrides["declaration_id"].fillna("").astype(str).str.strip()
    )
    if (overrides["declaration_id"] == "").any():
        raise ValueError(f"Overrides file {path} contains a blank declaration_id")

    for column in OPTIONAL_OVERRIDE_COLUMNS:
        overrides[column] = overrides[column].fillna("").astype(str).str.strip()

    duplicate_ids = sorted(
        overrides.loc[overrides["declaration_id"].duplicated(), "declaration_id"].unique()
    )
    if duplicate_ids:
        raise ValueError(
            f"Overrides file {path} has duplicate declaration_id values: "
            + ", ".join(duplicate_ids)
        )

    for _, row in overrides.iterrows():
        value = row["hazard_category_override"]
        if pd.isna(value) or not str(value).strip():
            raise ValueError(
                f"Overrides file {path}, declaration_id {row['declaration_id']!r}: "
                "blank hazard_category_override"
            )
        if str(value).strip().lower() != EXCLUDE_SENTINEL:
            # Validate now, regardless of whether this id matches anything
            # in the current declarations CSV - see docstring above.
            resolve_override(value)

    return overrides


def apply_overrides(declarations, overrides):
    """Merge a sidecar overrides file into declarations by declaration_id.

    A sidecar entry always wins over anything already in the declarations
    CSV's own hazard_category_override column (if it even has one) - the
    sidecar is the durable, reviewed source of truth, and the generated CSV
    is not. Any declaration_id in the sidecar with no matching row in
    declarations is reported as a warning, not silently ignored: it usually
    means an upstream id changed, or that declaration was dropped by a newer
    collection run, and a reviewed override that no longer applies to
    anything should stay visible rather than quietly doing nothing.
    """
    declarations = declarations.copy()
    declarations["declaration_id"] = declarations["declaration_id"].astype(str)
    if "hazard_category_override" not in declarations.columns:
        declarations["hazard_category_override"] = ""
    declarations["override_review_note"] = ""
    declarations["override_source_url"] = ""

    known_ids = set(declarations["declaration_id"])
    unmatched = []
    for _, row in overrides.iterrows():
        declaration_id = row["declaration_id"]
        if declaration_id not in known_ids:
            unmatched.append(declaration_id)
            continue
        mask = declarations["declaration_id"] == declaration_id
        declarations.loc[mask, "hazard_category_override"] = row["hazard_category_override"]
        declarations.loc[mask, "override_review_note"] = row["review_note"]
        declarations.loc[mask, "override_source_url"] = row["source_url"]

    if unmatched:
        print(
            f"WARNING: {len(unmatched)} override(s) in the sidecar file did not "
            "match any declaration_id in the current declarations CSV (the "
            "declaration may have been removed or renumbered by a newer "
            "collection run): " + ", ".join(unmatched),
            file=sys.stderr,
        )
    return declarations


def resolve_allowed_types(
    description, hazard_filter, unmatched_hazard_policy, override=None
):
    """Decide which NCEI EVENT_TYPE values a declaration's storm search should
    be restricted to, and flag when its description didn't match any known
    hazard keyword.

    Returns (allowed_types, ambiguous):
      - override is present (see resolve_override): allowed_types is the
        reviewer-supplied set, ambiguous=False. A human already resolved
        this declaration, so it is never flagged as ambiguous and always
        wins over both the keyword guess and hazard_filter/--no-hazard-filter.
      - hazard_filter is False (--no-hazard-filter): allowed_types=set()
        (no restriction, search every event type), ambiguous=False. This is
        an explicit, deliberate user choice, so nothing is flagged.
      - description matched at least one hazard keyword: allowed_types is
        that keyword-derived set, ambiguous=False.
      - description matched NO hazard keyword: ambiguous=True, and
        allowed_types depends on unmatched_hazard_policy:
          "skip" (default): allowed_types=None, meaning "match nothing".
            An unclassifiable description should not silently pull in every
            NCEI event recorded statewide in the window - that was the bug.
          "all": allowed_types=set() (no restriction), reproducing the old
            behavior, but only when explicitly requested, and always flagged
            by the caller as ambiguous so it shows up in the run's output.
    """
    resolved_override = resolve_override(override)
    if resolved_override is not None:
        return resolved_override, False
    if not hazard_filter:
        return set(), False
    categories = compatible_event_types(description)
    if categories:
        return categories, False
    if unmatched_hazard_policy == "all":
        return set(), True
    return None, True


def events_near_date(state, center_date, window_days, filenames, allowed_types):
    """Return NCEI events for a state within window_days of center_date.

    allowed_types (see resolve_allowed_types):
      - None: matches nothing. Used when hazard filtering is on, the
        description matched no recognized keyword, and the caller's
        unmatched-hazard policy is "skip" (the default).
      - falsy (empty set): no restriction; every recorded event type in the
        window is returned. Used for --no-hazard-filter and for the explicit
        --unmatched-hazard-policy all opt-in.
      - non-empty set: only events whose EVENT_TYPE is in this set.
    """
    if allowed_types is None:
        return pd.DataFrame(columns=EVENT_COLUMNS)

    start = center_date - timedelta(days=window_days)
    end = center_date + timedelta(days=window_days)
    frames = [
        get_year_events(year, filenames, state)
        for year in range(start.year, end.year + 1)
    ]
    frames = [frame for frame in frames if not frame.empty]
    if not frames:
        return pd.DataFrame()
    events = pd.concat(frames, ignore_index=True)
    mask = (
        (events["BEGIN_DATE_TIME"].dt.date >= start)
        & (events["BEGIN_DATE_TIME"].dt.date <= end)
    )
    matches = events.loc[mask]
    if allowed_types:
        matches = matches[matches["EVENT_TYPE"].isin(allowed_types)]
    return matches


def parse_damage(value):
    """Convert NCEI damage values such as 200K or 1.5M to dollars."""
    if pd.isna(value):
        return 0.0
    text = str(value).strip().upper()
    if not text:
        return 0.0
    multipliers = {"K": 1_000.0, "M": 1_000_000.0, "B": 1_000_000_000.0}
    multiplier = multipliers.get(text[-1], 1.0)
    if text[-1] in multipliers:
        text = text[:-1]
    try:
        return float(text) * multiplier
    except ValueError:
        return 0.0


def build_severity_summary(result):
    """Aggregate reported human and monetary impacts by NCEI area."""
    frame = result.copy()
    frame["damage_property_usd"] = frame["DAMAGE_PROPERTY"].apply(parse_damage)
    frame["damage_crops_usd"] = frame["DAMAGE_CROPS"].apply(parse_damage)
    declaration_fields = [
        column for column in DECLARATION_COLUMNS if column in frame.columns
    ]
    summary = (
        frame.groupby(
            declaration_fields
            + [
                "CZ_TYPE",
                "area_type",
                "CZ_FIPS",
                "CZ_NAME",
            ],
            dropna=False,
        )
        .agg(
            deaths_direct=("DEATHS_DIRECT", "sum"),
            injuries_direct=("INJURIES_DIRECT", "sum"),
            damage_property_usd=("damage_property_usd", "sum"),
            damage_crops_usd=("damage_crops_usd", "sum"),
            event_types=("EVENT_TYPE", lambda values: ", ".join(sorted(set(values)))),
            event_count=("EVENT_TYPE", "count"),
        )
        .reset_index()
    )
    summary["total_damage_usd"] = (
        summary["damage_property_usd"] + summary["damage_crops_usd"]
    )
    return summary.sort_values(
        ["date_signed", "declaration_id", "deaths_direct", "injuries_direct", "total_damage_usd"],
        ascending=[True, True, False, False, False],
    )


def validate_declarations(frame):
    required = {"eo_number", "event_description", "date_signed"}
    missing = sorted(required.difference(frame.columns))
    if missing:
        raise ValueError("Declaration CSV is missing: " + ", ".join(missing))


